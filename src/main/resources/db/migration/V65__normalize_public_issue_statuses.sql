UPDATE facility_review
SET review_status = 'UNDER_REVIEW'
WHERE review_status IN ('INSPECTION_REQUIRED', 'ACTION_IN_PROGRESS');

UPDATE public_issues
SET status = 'UNDER_REVIEW'
WHERE status IN ('INSPECTION_REQUIRED', 'ACTION_IN_PROGRESS');

ALTER TABLE facility_review
    MODIFY COLUMN review_status ENUM('PENDING','UNDER_REVIEW','COMPLETED') NULL;

ALTER TABLE public_issues
    MODIFY COLUMN status ENUM('RECEIVED','UNDER_REVIEW','COMPLETED')
    NOT NULL DEFAULT 'RECEIVED';
